let lang: Lang = "zh";
const listeners = new Set<() => void>();

export function setLang(l: Lang) {
  if (l === lang) return;
  lang = l;
  listeners.forEach((f) => f());
}

export function currentLang(): Lang {
  return lang;
}

export type TKey = keyof typeof dict.zh;

export function useT() {
  const [, force] = useReducer((x: number) => x + 1, 0);
  useEffect(() => {
    listeners.add(force);
    return () => {
      listeners.delete(force);
    };
  }, []);
  return (key: TKey, params?: Record<string, string | number>): string => {
    let s = dict[lang][key] ?? dict.zh[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        s = s.replace(`{${k}}`, String(v));
      }
    }
    return s;
  };
}

/** 启动时调用：读取持久化语言并跟随设置页修改。 */
let initialized = false;
export function initLang() {
  if (initialized) return;
  initialized = true;
  ipc
    .getUiSettings()
    .then((u) => setLang((u.lang as Lang) ?? "zh"))
    .catch(() => {}); // 读取失败保持默认语言，设置页可再改
  // 应用生命周期监听：模块单例存活期间永不退订（有意为之）；
  // 注册失败则语言固定为默认，避免未处理 rejection（#562-7）
  ipc
    .onLang((l) => setLang((l as Lang) ?? "zh"))
    .catch(() => {});
}
